import tempfile
import unittest
from abc import ABC
from typing import Literal

from pydantic import BaseModel, ConfigDict, ValidationError

from py_organelles.schema_versioning import BaseSchemaVersionedModel


class StrictConfiguredModel(BaseModel, ABC):
    """Stands in for a project's own configured base model."""

    model_config = ConfigDict(strict=True, extra="forbid")


class StrictSchemaVersionedModel(StrictConfiguredModel, BaseSchemaVersionedModel, ABC):
    """A project's versioned base, mixing its configuration into the library's base."""


class Kettle(StrictSchemaVersionedModel):
    type: Literal["Kettle"] = "Kettle"
    schema_version: Literal[2] = 2
    volume: float


class TestBaseSchemaVersionedModel(unittest.TestCase):
    """.. note:: Generated by Claude Opus 5.5."""

    def test_file_io(self) -> None:
        """A model written to a file reads back equal."""
        model = Kettle(volume=1.5)
        with tempfile.TemporaryFile(mode="w+") as text_io:
            model.write(text_io)
            text_io.seek(0)
            model_read = Kettle.read(text_io)

        self.assertEqual(model, model_read)

    def test_sets_no_model_config(self) -> None:
        """The library base adds no configuration of its own."""
        self.assertEqual(BaseSchemaVersionedModel.model_config, BaseModel.model_config)

    def test_mixed_in_config_applies(self) -> None:
        """A project's configuration survives being mixed with the library base."""
        self.assertTrue(issubclass(Kettle, BaseSchemaVersionedModel))
        with self.assertRaises(ValidationError):
            Kettle.model_validate({"volume": "1.5"})  # strict: no str -> float coercion
        with self.assertRaises(ValidationError):
            Kettle.model_validate({"volume": 1.5, "spout": True})  # extra="forbid"

    def test_schema_version_required(self) -> None:
        """Without a subclass default, ``schema_version`` must be supplied."""

        class Unversioned(BaseSchemaVersionedModel):
            pass

        with self.assertRaises(ValidationError):
            Unversioned.model_validate({})
        self.assertEqual(Unversioned.model_validate({"schema_version": 3}).schema_version, 3)
